def candidates_for(character, ctype, xien_list):
    """(シエン名リスト, 確認済みか) を返す。未定義なら全ペア代表にフォールバック。"""
    entry = AVAILABLE.get(character)
    if isinstance(entry, dict):
        names = entry.get(ctype) or []
    else:
        names = entry or []
    if names:
        return list(names), character in VERIFIED
    # 相異なる [基本,乱数] ペアごとに 1 つずつ代表を取る
    seen, names = set(), []
    for n, p in xien_list.items():
        key = tuple(p)
        if key not in seen:
            seen.add(key)
            names.append(n)
    return names, False


def same_pair_names(name, xien_list):
    """name と数値的に等価なシエン名を全部返す（結果表示用）。"""
    p = tuple(xien_list[name])
    return [n for n, q in xien_list.items() if tuple(q) == p]
